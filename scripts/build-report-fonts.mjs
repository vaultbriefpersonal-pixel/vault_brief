// Encodes the report typefaces as committed base64 modules.
//
// A HUMAN runs this; the output is committed. It never runs in CI or on
// Vercel — same discipline as the migration scripts, and for a related
// reason: the artifact it produces is load-bearing at runtime in two separate
// deployments, so it should change only when someone means it to.
//
//   node scripts/build-report-fonts.mjs
//
//
// WHY BASE64 AND NOT A FILE PATH
//
// The PDF renders in TWO runtimes. The Vercel Lambda serves
// /api/reports/[reportId]/pdf and two tRPC procedures; the Trigger.dev worker
// runs auto-generate-reports.ts, reachable because trigger.config.ts declares
// `dirs: ["./src/server/jobs"]`. Next's `outputFileTracingIncludes` does
// nothing for the Trigger build — it has its own bundler and its own
// `additionalFiles` mechanism, which is exactly why that config already needs
// `build.external` for resvg.
//
// A filesystem approach is therefore two mechanisms, each able to fail
// silently, and the one most likely to break is the unattended cron path
// where the error is swallowed and the founder simply never gets a report.
// A bundled module cannot fail that way: if the import resolved, the bytes
// are there.
//
//
// WHY THE FONTS ARE NOT SUBSETTED
//
// They were, briefly. `subset-font` (harfbuzz) cut the four faces from 918 KB
// to 522 KB of base64 — and produced fonts whose LAST one or two glyphs had
// out-of-bounds offsets in the glyf/loca tables. fontkit threw
// "RangeError: Offset is outside the bounds of the DataView" from
// TTFGlyph._getCBox during layout, i.e. a hard crash on the PDF path, which
// is the product's actual deliverable. Verified precisely: the shipped
// subsets had 2 (mono) and 1 (serif) broken glyphs; the untouched source
// fonts have zero.
//
// The saving was not worth a crash class, and it buys less than it appears
// to: pdfkit calls createSubset()/includeGlyph() when it EMBEDS a font, so
// the generated PDFs are the same size either way. The cost of shipping full
// faces is bundle bytes in two server builds, and nothing else.
//
// If someone revisits this, the bar is `node --import tsx scripts/smoke-pdf.mjs`
// passing AND the glyph sweep in pdf-fonts.test.ts staying green.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const FONT_DIR = join(HERE, "..", "src", "assets", "fonts");
const OUT_DIR = join(FONT_DIR, "generated");

const FACES = [
  { file: "Spectral-Regular.ttf", constName: "SPECTRAL_REGULAR_B64" },
  { file: "Spectral-SemiBold.ttf", constName: "SPECTRAL_SEMIBOLD_B64" },
  { file: "Spectral-Italic.ttf", constName: "SPECTRAL_ITALIC_B64" },
  { file: "IBMPlexMono-Regular.ttf", constName: "PLEX_MONO_REGULAR_B64" },
];

mkdirSync(OUT_DIR, { recursive: true });

let rawTotal = 0;
let outTotal = 0;

for (const { file, constName } of FACES) {
  const src = join(FONT_DIR, file);
  if (!existsSync(src)) {
    throw new Error(
      `Missing ${file}. The source TTFs are committed in src/assets/fonts/ ` +
        `alongside their OFL licences.`
    );
  }

  const bytes = readFileSync(src);
  const b64 = bytes.toString("base64");

  const banner =
    `// GENERATED by scripts/build-report-fonts.mjs — do not edit by hand.\n` +
    `// Source: src/assets/fonts/${file} (OFL 1.1).\n` +
    `// Base64 rather than a file read: the PDF renders in both the Vercel\n` +
    `// Lambda and the Trigger.dev worker, and only a bundled module is\n` +
    `// guaranteed to resolve in both. See the script header for why this is\n` +
    `// the full face and not a subset.\n`;

  writeFileSync(
    join(OUT_DIR, file.replace(/\.ttf$/, "") + ".base64.ts"),
    `${banner}export const ${constName} =\n  "${b64}";\n`,
    "utf8"
  );

  rawTotal += bytes.length;
  outTotal += b64.length;
  console.log(
    `${file.padEnd(28)} ${kb(bytes.length).padStart(9)} -> ${kb(b64.length).padStart(9)} base64`
  );
}

console.log(
  `\nTotal: ${kb(rawTotal)} raw -> ${kb(outTotal)} base64 across ${FACES.length} faces.`
);
console.log(
  "Verify with:\n" +
    "  npx vitest run src/server/services/pdf-fonts.test.ts\n" +
    "  node --import tsx scripts/smoke-pdf.mjs"
);

function kb(bytes) {
  return `${(bytes / 1024).toFixed(0)} KB`;
}
